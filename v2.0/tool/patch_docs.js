function repl(file, pairs) {
  const p = path.join(t, file);
  let txt = fs.readFileSync(p, 'utf8');
  let n = 0;
  for (const [a, b] of pairs) {
    if (txt.includes(a)) {
      const c = txt.split(a).length - 1;
      txt = txt.split(a).join(b);
      n += c;
    } else {
      console.log('  !! 未匹配: ' + a.slice(0, 40));
    }
  }
  fs.writeFileSync(p, txt, 'utf8');
  console.log(file + ' 替换 ' + n + ' 处');
}

