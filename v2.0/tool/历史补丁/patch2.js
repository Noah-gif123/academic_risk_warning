/* patch2.js — 按教师端补充的第二轮确认结果更新 feature_content.json */
'use strict';
const fs = require('fs'), path = require('path');
const gen = __dirname;
const file = path.join(gen, 'feature_content.json');
const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
const B = doc.blocks;

const findH = (t, prefix) => B.findIndex(b => b.t === t && String(b.x).indexOf(prefix) === 0);
const h1 = x => findH('h1', x), h2 = x => findH('h2', x), h3 = x => findH('h3', x);

// ---------- 1. 覆盖率阈值：二分之一 / 1/2 → 三分之一 / 1/3 ----------
let n = 0;
const fix = s => String(s)
  .replace(/低于二分之一/g, '低于三分之一')
  .replace(/二分之一/g, '三分之一')
  .replace(/1\/2/g, '1/3');
JSON.stringify(B).length; // noop
function walk(o) {
  if (typeof o === 'string') { const v = fix(o); if (v !== o) { n++; return v; } return o; }
  if (Array.isArray(o)) return o.map(walk);
  if (o && typeof o === 'object') { const r = {}; for (const k in o) r[k] = walk(o[k]); return r; }
  return o;
}
doc.blocks = walk(B);
const B2 = doc.blocks;
console.log('覆盖率口径替换处数: ' + n);

// ---------- 2. 术语表：覆盖率说明 ----------
{
  const t = B2.find(b => b.t === 'table' && b.cap.indexOf('主要术语') >= 0);
  if (t) t.rows.forEach(r => { if (r[0] === '覆盖率') r[1] = '已点名课次占应完成课次的比例；低于三分之一时判低置信度'; });
}

