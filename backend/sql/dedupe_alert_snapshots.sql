-- =============================================================================
-- 一次性数据清理：把历史重复快照按"一人一课一天一条"去重
-- =============================================================================
-- 背景：方案A 之前，快照是随每条预警写入的，同一学生同一天同一课程会留下
--       多条内容相同的记录（触发 N 种预警类型就有 N+1 条），导致趋势图
--       同一天出现多个重复点。
-- 说明：保留每个 (student_id, course_id, snapshot_date) 中 id 最小的一条，
--       脚本可重复执行（已去重后不会删除任何行）。
-- =============================================================================

DELETE s1
FROM `alert_snapshot` s1
JOIN `alert_snapshot` s2
  ON s1.`student_id` = s2.`student_id`
 AND s1.`snapshot_date` = s2.`snapshot_date`
 AND s1.`id` > s2.`id`
 AND (
       (s1.`course_id` IS NULL AND s2.`course_id` IS NULL)
    OR (s1.`course_id` = s2.`course_id`)
     );
